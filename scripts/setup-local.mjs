import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const local=rel=>{const abs=path.resolve(root,rel);if(!abs.startsWith(root+path.sep))throw Error(`Path outside workspace: ${rel}`);return abs;};
for(const dir of ['assets/images','assets/videos','assets/audio','assets/logos/logo-chung','jobs','output/videos','output/previews','output/covers','output/posts','temp','tools','src/projects','src/generated','config'])fs.mkdirSync(local(dir),{recursive:true});
if(!fs.existsSync(local('config/voice-defaults.json')))fs.copyFileSync(local('config/voice-defaults.example.json'),local('config/voice-defaults.json'),fs.constants.COPYFILE_EXCL);
const registry='config/projects.local.json';
if(!fs.existsSync(local(registry)))fs.writeFileSync(local(registry),JSON.stringify({projects:[]},null,2)+'\n',{flag:'wx'});
const {projects}=JSON.parse(fs.readFileSync(local(registry),'utf8'));
if(!Array.isArray(projects))throw Error('projects must be an array');
const ids=new Set();
const imports=["import {Composition} from 'remotion';"];
const elements=[];
const modulePath=rel=>JSON.stringify(path.relative(local('src/generated'),local(rel)).split(path.sep).join('/').replace(/\.tsx$/,''));
for(const [i,entry]of projects.entries()){
 if(!/^[A-Za-z0-9-]+$/.test(entry.id)||ids.has(entry.id))throw Error('Invalid/duplicate composition ID');ids.add(entry.id);
 if(!/^[A-Za-z_$][\w$]*$/.test(entry.exportName))throw Error('Invalid component export');
 if(!entry.component.startsWith('src/projects/')||!entry.component.endsWith('.tsx')||!entry.job.startsWith('jobs/')||!entry.job.endsWith('.json'))throw Error('Expected a local component and job');
 for(const file of [entry.component,entry.job])if(!fs.existsSync(local(file)))throw Error(`Missing registered project file: ${file}`);
 imports.push(`import {${entry.exportName} as Video${i}} from ${modulePath(entry.component)};`,`import job${i} from ${modulePath(entry.job)};`);
 elements.push(`<Composition id=${JSON.stringify(entry.id)} component={Video${i}} durationInFrames={job${i}.format.durationInFrames} fps={job${i}.format.fps} width={job${i}.format.width} height={job${i}.format.height}/>`);
}
const code='// Generated by scripts/setup-local.mjs. Local only; do not edit.\n'+imports.join('\n')+'\nexport const LocalCompositions = () => <>\n'+elements.join('\n')+'\n</>;\n';
fs.writeFileSync(local('src/generated/local-compositions.tsx'),code);
console.log(`Local setup ready (${projects.length} project composition(s)). No models downloaded.`);
